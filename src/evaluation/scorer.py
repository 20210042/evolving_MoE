def normalize_math_answer(s):
    """Normalize regex extracted math answer."""
    if s is None:
        return ""
    # Remove whitespace, simple latex normalizations
    s = str(s).strip().replace(" ", "")
    # Remove common latex commands that don't change value for string match
    # (very basic)
    s = s.replace(r"\dfrac", r"\frac").replace(r"\tfrac", r"\frac")
    return s

def extract_math_answer(text):
    """Extract answer from \boxed{...} or Final Answer: ..."""
    if "Final Answer:" in text:
        return text.split("Final Answer:")[-1].strip()
    
    matches = re.findall(r'\\boxed\{(.*?)\}', text)
    if matches:
        return matches[-1] # Return the LAST boxed answer
    
    return text.strip()

