def clean_extracted_code(text):
    if not text:
        return ""
    # 💡 LLM이 가끔 뱉는 악성 공백(Non-Breaking Space) 치환
    text = text.replace('\xa0', ' ')
    
    code = extract_code_block(text)
    
    # 💡 시작 태그가 없어 추출에 실패했을 경우, 찌꺼기 백틱 강제 제거
    if not code:
        code = text.replace('```python\n', '').replace('```python', '').replace('```\n', '').replace('```', '')
        
    # 불필요한 종료 마커 제거
    for marker in ["END SOLUTION", "### SUCCESS", "### END"]:
        if marker in code:
            code = code.split(marker)[0]
            
    return code.strip()

def extract_helper_code(ground_truth):
    """
    Extract class definitions and import statements from ground truth.
    These may be needed by test code but not generated by the model.
    """
    if not ground_truth:
        return ""
    
    lines = ground_truth.replace('\r\n', '\n').replace('\r', '\n').split('\n')
    helper_lines = []
    in_class = False
    class_indent = 0
    
    for line in lines:
        stripped = line.lstrip()
        current_indent = len(line) - len(stripped)
        
        # Capture import statements
        if stripped.startswith('import ') or stripped.startswith('from '):
            helper_lines.append(line)
            continue
            
        # Capture class definitions
        if stripped.startswith('class '):
            in_class = True
            class_indent = current_indent
            helper_lines.append(line)
            continue
            
        # Continue capturing class body
        if in_class:
            if stripped and current_indent <= class_indent:
                in_class = False
            else:
                helper_lines.append(line)
                
    return '\n'.join(helper_lines)

def unsafe_execute(code, test_code, entry_point, result_queue, expected_name=None):
    """
    Executes the code + test_code.
    Returns 100.0 if successful (Pass), 0.0 otherwise (Fail).
    """
    # Capture stdout/stderr to suppress print output during test
    with contextlib.redirect_stdout(StringIO()), contextlib.redirect_stderr(StringIO()):
        try:
            local_env = {}
            # Execute the generated code first to define functions
            try:
                exec(code, globals(), local_env)
            except Exception as e:
                result_queue.put(0.0)
                return

            # Prepare test execution
            import tempfile
            import os
            import shutil
            
            with tempfile.TemporaryDirectory() as tmpdir:
                original_cwd = os.getcwd()
                os.chdir(tmpdir)
                try:
                    if "def check(" in test_code and entry_point:
                        # HumanEval style: check(candidate)
                        if entry_point not in local_env:
                            found = False
                            for key in local_env:
                                if callable(local_env[key]) and key != "check":
                                    local_env[entry_point] = local_env[key]
                                    found = True
                                    break
                            if not found:
                                result_queue.put(0.0)
                                return
                        
                        exec(test_code, globals(), local_env)
                        exec(f"check({entry_point})", globals(), local_env)
                    else:
                        # MBPP or other style: test_code contains assertions
                        if expected_name and expected_name not in local_env:
                            for key in list(local_env.keys()):
                                if callable(local_env[key]):
                                    local_env[expected_name] = local_env[key]
                                    break
                        exec(test_code, globals(), local_env)
                    
                    # If we got here without exception, it's a Pass
                    result_queue.put(100.0)
                finally:
                    os.chdir(original_cwd)
            
        except Exception:
            # Any error (AssertionError, SyntaxError, etc) is a Fail
            result_queue.put(0.0)

def evaluate_code_score(prediction, test_code, entry_point=None, expected_name=None, helper_code=None):
    """
    Run code in separate process with timeout.
    Returns score 0 or 100 (Pass@1).
    """
    # Extract code block
    code = clean_extracted_code(prediction)
    
    # Prepend helper code (classes, imports from ground truth)
    if helper_code:
        code = helper_code + "\n\n" + code
        
    queue = multiprocessing.Queue()
    
    p = multiprocessing.Process(target=unsafe_execute, args=(code, test_code, entry_point, queue, expected_name))
    p.start()
    p.join(timeout=3) # 3 second timeout
    
    if p.is_alive():
        p.terminate()
        p.join()
        return 0.0 # Timeout
    
    if not queue.empty():
        return queue.get()
    return 0.0 # Process died without output

def evaluate_ds1000_score(prediction, code_context):
    code = clean_extracted_code(prediction)

    full_script = f"""
{code_context}

solution_code = {repr(code)}

try:
    test_execution(solution_code)
    print("DS1000_PASS")
except Exception as e:
    print(f"DS1000_FAIL: {{e}}")
"""
    
    queue = multiprocessing.Queue()
    
    def run_ds_test(script, q):
        import contextlib
        from io import StringIO
        f = StringIO()
        import tempfile
        import os
        import shutil
        
        with tempfile.TemporaryDirectory() as tmpdir:
            original_cwd = os.getcwd()
            os.chdir(tmpdir)
            with contextlib.redirect_stdout(f), contextlib.redirect_stderr(f):
                try:
                    exec(script, globals())
                except Exception as e:
                    print(f"DS1000_EXEC_ERROR: {e}")
            os.chdir(original_cwd)
        
        output = f.getvalue()
        if "DS1000_PASS" in output:
            q.put(100.0)
        else:
            q.put(0.0)

    p = multiprocessing.Process(target=run_ds_test, args=(full_script, queue))
    p.start()
    p.join(timeout=10)
    
    if p.is_alive():
        p.terminate()
        p.join()
        return 0.0
        
    if not queue.empty():
        return queue.get()
    return 0.0

